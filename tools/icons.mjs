const FILLED = ['wrench', 'boat', 'checklist', 'log', 'plug', 'settings']

function pathOf(file) {
  const svg = readFileSync(join(src, file), 'utf8')
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (paths.length !== 1) throw new Error(`${file}: expected one path, found ${paths.length}`)
  return paths[0]
}

const lines = Object.entries(ICONS).map(([name, symbol]) => `  ${name}: '${pathOf(`${symbol}.svg`)}',`)
const filled = FILLED.map((name) => `  ${name}: '${pathOf(`${ICONS[name]}-fill.svg`)}',`)

writeFileSync(
  out,
  `/* eslint-disable */
// Generated by tools/icons.mjs from Material Symbols Rounded, weight 400.
// Material Symbols © Google, Apache License 2.0. Do not edit by hand.

export const ICON_PATHS = {
${lines.join('\n')}
} as const

export const FILLED_PATHS: Partial<Record<keyof typeof ICON_PATHS, string>> = {
${filled.join('\n')}
}
`
)

// Report icons nothing refers to, so the map stays honest.
const used = new Set()
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.tsx?$/.test(f) && !f.startsWith('icons.gen')) {
      const text = readFileSync(p, 'utf8')
      for (const name of Object.keys(ICONS)) if (new RegExp(`['"]${name}['"]`).test(text)) used.add(name)
    }
  }
}
walk(join(root, 'web/src'))
const unused = Object.keys(ICONS).filter((n) => !used.has(n))
console.log(`wrote ${Object.keys(ICONS).length} icons (${FILLED.length} filled) to ${out}`)
if (unused.length) console.log(`not referenced: ${unused.join(', ')}`)
